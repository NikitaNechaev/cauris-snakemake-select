#!/usr/bin/env python3
"""TEN / C. auris step 18: extract translated miniprot matches into 09_protein_sequences.

Inputs (unchanged):
  04_summarize_clusters/auris_priority.faa
  08_population/qc/genome_manifest.tsv
  08_population/results/candidate_genome_details.tsv
  08_population/results/mapping_audit/mapping_audit.tsv
  08_population/results/clade_typing/clade_assignments.tsv
Output: 09_protein_sequences/

Requires Python >=3.9 and miniprot with -T 12, --gff and --trans.
Translation is generated by miniprot, not by naive genomic ORF translation.
Passes the same indexing/search options as the original map (-T 12 -I --gff),
plus --trans, and matches each result to the previously selected GFF hit.
"""
from __future__ import annotations
import argparse, csv, hashlib, json, os, re, shutil, subprocess, sys, tempfile
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

VERSION = "1.0.0"
BAD_FLAGS = {"multiple_strict_loci", "frameshift_in_best", "stop_codon_in_best",
             "invalid_genome_coordinates", "near_contig_end", "contig_name_not_found",
             "missing_genome_coordinates"}
AA_RE = re.compile(r"^[A-Z*]+$")


def read_tsv(path: Path, required=()):
    if not path.is_file():
        raise FileNotFoundError(f"Missing input: {path}")
    with path.open(encoding="utf8", newline="") as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        if not reader.fieldnames or not set(required) <= set(reader.fieldnames):
            raise ValueError(f"Expected columns {sorted(required)} in {path}; got {reader.fieldnames}")
        rows = list(reader)
    return rows


def write_tsv(path: Path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=header, delimiter="\t", extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def write_json_atomic(path: Path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf8")
    os.replace(tmp, path)


def sha256(path: Path):
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def fasta_dict(path: Path):
    results, name, parts = {}, None, []
    with path.open(encoding="utf8") as fh:
        for line in fh:
            if line.startswith(">"):
                if name:
                    results[name] = "".join(parts).upper()
                name, parts = line[1:].split()[0], []
                if name in results:
                    raise ValueError(f"Duplicated FASTA ID {name}")
            else:
                parts.append(line.strip())
        if name:
            results[name] = "".join(parts).upper()
    if not results:
        raise ValueError(f"Empty FASTA: {path}")
    return results


def file_state(path: Path):
    s = path.stat()
    return [str(path.resolve()), s.st_size, s.st_mtime_ns]


def parse_paf(fields):
    # Fields are PAF, with ##PAF prefix removed.
    if len(fields) < 12:
        raise ValueError(f"Truncated PAF line: {fields[:5]}")
    tags = {}
    for f in fields[12:]:
        parts = f.split(":", 2)
        if len(parts) == 3:
            tags[parts[0]] = parts[2]
    return {"candidate": fields[0], "qlen": int(fields[1]),
            "qstart": int(fields[2]), "qend": int(fields[3]),
            "strand": fields[4], "contig": fields[5], "contig_len": int(fields[6]),
            "tstart": int(fields[7]), "tend": int(fields[8]),
            "fs": int(tags.get("fs", "0")), "st": int(tags.get("st", "0"))}


def parse_miniprot_translated(lines):
    """Yield PAF+STA pairs. In --gff --trans output: ##PAF, ##STA, then GFF features.

    A new PAF without STA is a malformed alignment for extraction; detect it.
    """
    pending = None
    for line in lines:
        if line.startswith("##PAF\t"):
            if pending is not None:
                raise ValueError(f"Missing ##STA after PAF for {pending['candidate']}")
            pending = parse_paf(line.rstrip("\n").split("\t")[1:])
        elif line.startswith("##STA\t"):
            if pending is None:
                raise ValueError("##STA without preceding ##PAF")
            seq = line.rstrip("\n").split("\t", 1)[1].upper().strip()
            if not seq or not AA_RE.fullmatch(seq):
                raise ValueError(f"Invalid translated sequence for {pending['candidate']}: {seq[:30]!r}")
            yield pending, seq
            pending = None
        elif line.startswith("#"):
            continue
    if pending is not None:
        raise ValueError(f"Missing ##STA at end for {pending['candidate']}")


def matched_to_old(hit, orig):
    """Match a PAF hit with the exact previously picked GFF alignment.

    PAF tstart is 0-based; GFF mRNA may extend by 3 bp for a terminal stop.
    """
    if (hit["candidate"] != orig["candidate"] or hit["contig"] != orig["contig"]
            or hit["strand"] != orig["strand"]):
        return False
    try:
        old_start = int(orig["genome_start"])
        old_end = int(orig["genome_end"])
        q_start = int(orig["protein_start"])
        q_end = int(orig["protein_end"])
    except (ValueError, TypeError):
        return False
    return (hit["qstart"] + 1 == q_start and hit["qend"] == q_end
            and abs(hit["tstart"] + 1 - old_start) <= 3
            and abs(hit["tend"] - old_end) <= 3)


def choose_translated(acc, seqs, original_by_candidate, audit_by_candidate, candidates):
    chosen = {}
    matches = defaultdict(list)
    extra_paf = 0
    for hit, aa in seqs:
        cid = hit["candidate"]
        orig = original_by_candidate.get(cid)
        if orig is None or orig["status"] != "pass":
            continue
        if matched_to_old(hit, orig):
            matches[cid].append((hit, aa))
        else:
            extra_paf += 1
    problems = []
    for cid, orig in original_by_candidate.items():
        if orig["status"] != "pass":
            continue
        audit = audit_by_candidate[cid]
        flags = set(filter(None, audit.get("flags", "").split(";")))
        bad = sorted(BAD_FLAGS & flags)
        hits = matches.get(cid, [])
        reason = None
        if len(hits) == 0:
            reason = "no_exact_match_to_previous_gff"
        elif len(hits) > 1:
            reason = "ambiguous_translation_multiple_same_locus"
        elif bad:
            reason = "qc_flags:" + ",".join(bad)
        else:
            hit, translated = hits[0]
            if hit["qlen"] != len(candidates[cid]):
                reason = "query_length_changed"
            elif hit["fs"] or hit["st"]:
                reason = "frameshift_or_stop_in_translation"
            else:
                aa = translated.rstrip("*")
                if "*" in aa:
                    reason = "internal_stop_codon"
                elif not aa or len(aa) < 20:
                    reason = "unexpected_short_translation"
                elif any(ch not in "ACDEFGHIKLMNPQRSTVWYXUO" for ch in aa):
                    reason = "unknown_amino_acid_character"
                else:
                    chosen[cid] = {"sequence": aa, "qstart": hit["qstart"] + 1,
                                   "qend": hit["qend"], "contig": hit["contig"],
                                   "tstart": hit["tstart"] + 1, "tend": hit["tend"],
                                   "strand": hit["strand"], "clade": audit.get("clade", "Unassigned"),
                                   "identity_pct": orig["best_identity_pct"],
                                   "coverage_pct": orig["best_coverage_pct"],
                                   "flags": audit.get("flags", "")}
        if reason:
            problems.append({"assembly": acc, "candidate": cid, "reason": reason,
                             "status": orig["status"], "flags": audit.get("flags", "")})
    return chosen, problems, extra_paf


def extract_one(miniprot, threads, genome, proteins, accession, original, audit, candidates, output_log):
    cmd = [miniprot, "-T", "12", "-I", "-t", str(threads), "--gff", "--trans",
           str(genome), str(proteins)]
    with output_log.open("w", encoding="utf8") as log:
        log.write("COMMAND: " + " ".join(cmd) + "\n")
        log.flush()
        process = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=log,
                                   text=True, encoding="utf8", errors="replace")
        try:
            sequences = list(parse_miniprot_translated(process.stdout))
            rc = process.wait()
            if rc:
                raise RuntimeError(f"miniprot returned {rc}; log: {output_log}")
        except BaseException:
            process.kill()
            process.wait()
            raise
    chosen, problems, others = choose_translated(accession, sequences, original, audit, candidates)
    return {"chosen": chosen, "issues": problems, "nonmatching_other_paf": others,
            "total_translated_alignments": len(sequences)}


def write_fasta(path: Path, records):
    with path.open("w", encoding="utf8") as out:
        for name, seq in records:
            out.write(">" + name + "\n")
            for k in range(0, len(seq), 80):
                out.write(seq[k:k + 80] + "\n")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent,
                        help="TEN project root (default: parent of scripts/)")
    parser.add_argument("--out", type=Path, help="Output directory (default: <root>/09_protein_sequences)")
    parser.add_argument("--threads", type=int, default=14, help="Threads per miniprot call")
    parser.add_argument("--limit", type=int, default=0, help="Process at most this many new genomes; 0=all")
    parser.add_argument("--cache-dir", type=Path, help="Override the assembly cache directory")
    parser.add_argument("--alignment-log", type=Path, help="Aligner log for --assembly")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--assembly", help="Extract one assembly and write its cache record")
    modes.add_argument("--collect", action="store_true", help="Require existing cache records and assemble output")
    parser.add_argument("--force", action="store_true", help="Re-extract even when cached result is valid")
    parser.add_argument("--miniprot", default="miniprot", help="miniprot executable or its absolute path")
    args = parser.parse_args(argv)
    if args.threads < 1 or args.limit < 0:
        parser.error("--threads must be >=1, --limit must be >=0")
    if args.collect and (args.force or args.limit):
        parser.error("--collect cannot be combined with --force or --limit")
    if args.alignment_log and not args.assembly:
        parser.error("--alignment-log requires --assembly")
    root = args.root.expanduser().resolve()
    out = (args.out or root / "09_protein_sequences").expanduser().resolve()
    pop = root / "08_population"
    proteins = root / "04_summarize_clusters/auris_priority.faa"
    manifest_path = pop / "qc/genome_manifest.tsv"
    details_path = pop / "results/candidate_genome_details.tsv"
    audit_path = pop / "results/mapping_audit/mapping_audit.tsv"
    clades_path = pop / "results/clade_typing/clade_assignments.tsv"
    originals = read_tsv(details_path, {"assembly", "candidate", "status", "contig", "strand", "genome_start", "genome_end", "protein_start", "protein_end"})
    audits = read_tsv(audit_path, {"assembly", "candidate", "status", "flags", "clade"})
    clades = read_tsv(clades_path, {"assembly", "assigned_clade"})
    manifest = read_tsv(manifest_path, {"assembly", "fasta"})
    candidates = fasta_dict(proteins)
    original_by_asm, audit_by_asm = defaultdict(dict), defaultdict(dict)
    for r in originals:
        if r["candidate"] in original_by_asm[r["assembly"]]:
            raise ValueError("Duplicate original mapping entry: " + r["assembly"] + ":" + r["candidate"])
        original_by_asm[r["assembly"]][r["candidate"]] = r
    for r in audits:
        audit_by_asm[r["assembly"]][r["candidate"]] = r
    clade_lookup = {r["assembly"]: r["assigned_clade"] for r in clades}
    if len(clade_lookup) != len(clades):
        raise ValueError("Duplicate clade assignment")
    for r in manifest:
        acc = r["assembly"]
        if set(original_by_asm[acc]) != set(candidates) or set(audit_by_asm[acc]) != set(candidates):
            raise ValueError(f"Incomplete mapping / audit for {acc}")
        if acc not in clade_lookup:
            raise ValueError(f"No clade assignment for {acc}")
        if not Path(r["fasta"]).is_file():
            raise FileNotFoundError(f"Missing genome: {r['fasta']}")
    if len(manifest) != len({r["assembly"] for r in manifest}):
        raise ValueError("Duplicate assembly in manifest")
    if len(originals) != len(manifest) * len(candidates):
        raise ValueError("Unexpected number of original mappings")
    executable = shutil.which(args.miniprot)
    if not executable:
        raise FileNotFoundError("miniprot executable missing in PATH: " + args.miniprot)
    executable = str(Path(executable).resolve())
    out.mkdir(parents=True, exist_ok=True)
    cache_dir, logs_dir = args.cache_dir or out / "cache", out / "logs"
    cache_dir.mkdir(parents=True, exist_ok=True)
    if not args.alignment_log and not args.collect:
        logs_dir.mkdir(exist_ok=True)
    input_hashes = {"protein_sha256": sha256(proteins), "mapping_sha256": sha256(details_path),
                    "audit_sha256": sha256(audit_path), "clades_sha256": sha256(clades_path)}
    loaded = {}
    new_count = skip_count = 0
    tasks = [row for row in manifest if row["assembly"] == args.assembly] if args.assembly else manifest
    if not tasks:
        raise ValueError(f"Assembly {args.assembly} is missing from the QC manifest")
    for idx, row in enumerate(tasks, 1):
        acc = row["assembly"]
        genome = Path(row["fasta"]).resolve()
        old_gff = pop / "alignments" / f"{acc}.gff"
        if not old_gff.exists():
            raise FileNotFoundError(f"Missing original GFF for {acc}: {old_gff}")
        expected = {"version": VERSION, "assembly": acc, "genome": file_state(genome),
                    "original_gff": file_state(old_gff), "miniprot": executable,
                    "code": 12, "input_hashes": input_hashes}
        cache = cache_dir / f"{acc}.json"
        obj = None
        if cache.is_file() and not args.force:
            try:
                prev = json.loads(cache.read_text(encoding="utf8"))
                if prev.get("stamp") == expected:
                    obj = prev
                    skip_count += 1
            except (OSError, json.JSONDecodeError):
                pass
        if obj is None:
            if args.collect:
                raise RuntimeError(f"Missing or stale extraction cache for {acc}: {cache}")
            print(f"[EXTRACT] {idx}/{len(tasks)} {acc}", flush=True)
            result = extract_one(executable, args.threads, genome, proteins, acc,
                                 original_by_asm[acc], audit_by_asm[acc], candidates,
                                 args.alignment_log or logs_dir / f"{acc}.log")
            obj = {"stamp": expected, **result}
            write_json_atomic(cache, obj)
            new_count += 1
        loaded[acc] = obj
        if args.limit and new_count >= args.limit:
            print(f"[TEST LIMIT] Newly processed {new_count} assemblies; others remain pending")
            break
    if args.assembly:
        return 0
    if len(loaded) != len(manifest):
        print(f"[PARTIAL] {len(loaded)}/{len(manifest)} complete. Re-run without --limit to create final FASTA files.")
        return 0
    by_cand = defaultdict(list)
    inv, issues = [], []
    for acc in [r["assembly"] for r in manifest]:
        obj = loaded[acc]
        issues.extend(obj["issues"])
        for cid, info in obj["chosen"].items():
            if info["clade"] != clade_lookup[acc]:
                raise ValueError(f"Stale clade annotation in audit for {acc}: audit={info['clade']}, current={clade_lookup[acc]}. Rerun step17 audit.")
            by_cand[cid].append((acc, info))
            inv.append({"assembly": acc, "candidate": cid, "clade": info["clade"],
                        "aa_length": len(info["sequence"]), "sha256_aa": hashlib.sha256(info["sequence"].encode()).hexdigest(),
                        "identity_pct": info["identity_pct"], "coverage_pct": info["coverage_pct"],
                        "contig": info["contig"], "genome_start": info["tstart"],
                        "genome_end": info["tend"], "strand": info["strand"], "flags": info["flags"]})
    cand_folder = out / "by_candidate"
    unique_folder = out / "by_candidate_unique"
    cand_folder.mkdir(exist_ok=True)
    unique_folder.mkdir(exist_ok=True)
    alleles = []
    for cid in candidates:
        records = by_cand.get(cid, [])
        write_fasta(cand_folder / f"{cid}.faa", [(f"{cid}|{acc}", info["sequence"]) for acc, info in records])
        unique = defaultdict(list)
        for acc, info in records:
            unique[info["sequence"]].append(acc)
        write_fasta(unique_folder / f"{cid}.faa", [
            (f"{cid}|allele_{i:03d}|n={len(accs)}", seq)
            for i, (seq, accs) in enumerate(sorted(unique.items(), key=lambda x: (-len(x[1]), x[0])), 1)])
        for i, (seq, accs) in enumerate(sorted(unique.items(), key=lambda x: (-len(x[1]), x[0])), 1):
            alleles.append({"candidate": cid, "allele": f"allele_{i:03d}",
                            "count": len(accs), "assemblies": ",".join(sorted(accs)),
                            "sequence_sha256": hashlib.sha256(seq.encode()).hexdigest()})
    write_tsv(out / "sequence_inventory.tsv", ["assembly", "candidate", "clade", "aa_length", "sha256_aa",
                                               "identity_pct", "coverage_pct", "contig", "genome_start",
                                               "genome_end", "strand", "flags"], inv)
    write_tsv(out / "extraction_issues.tsv", ["assembly", "candidate", "reason", "status", "flags"], issues)
    write_tsv(out / "allele_counts.tsv", ["candidate", "allele", "count", "assemblies", "sequence_sha256"], alleles)
    n_pass = sum(r["status"] == "pass" for r in originals)
    summary = {"timestamp_utc": datetime.now(timezone.utc).isoformat(), "project_root": str(root),
               "output": str(out), "n_assemblies": len(manifest), "n_candidates": len(candidates),
               "candidate_assembly_pairs": len(originals), "n_original_pass": n_pass,
               "n_sequences_extracted_clean": len(inv), "n_extraction_issues_for_pass": len(issues),
               "distinct_aa_alleles": len(alleles), "newly_processed_assemblies": new_count,
               "cached_assemblies": skip_count, "translation_table": 12,
               "method": "miniprot --gff --trans; matches original GFF best hits and excludes critical QC flags",
               "biological_limits": "Translated alignment-derived proteins are not experimentally validated ORFs, surface localization, expression, or antigenicity."}
    write_json_atomic(out / "extraction_summary.json", summary)
    print("[DONE] " + json.dumps({k: summary[k] for k in ("n_assemblies", "n_candidates", "n_original_pass", "n_sequences_extracted_clean", "distinct_aa_alleles")}, ensure_ascii=False))
    print("[OUTPUT] " + str(out))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        sys.exit(1)
